CREATE OR REPLACE VIEW V_CUSTOMER_SUMMARY AS
SELECT c.*, c.WALLET_SHARE_PCT / 100.0 AS WALLET_SHARE_RATIO,
       l.BASE_COST_USD, l.STRESS_COST_USD, l.FIXED_COST_USD, l.REBATE_USD,
       l.BASE_COST_USD / 0.25 AS BREAK_EVEN_REVENUE_USD
FROM DIM_CUSTOMER c
LEFT JOIN (
    SELECT CUSTOMER_ID, SUM(BASE_COST_USD) AS BASE_COST_USD,
           SUM(STRESS_COST_USD) AS STRESS_COST_USD,
           SUM(CASE WHEN BENEFIT_ID <> 'B01' THEN BASE_COST_USD ELSE 0 END) AS FIXED_COST_USD,
           SUM(CASE WHEN BENEFIT_ID = 'B01' THEN BASE_COST_USD ELSE 0 END) AS REBATE_USD
    FROM FACT_LOYALTY_COST GROUP BY CUSTOMER_ID
) l ON c.CUSTOMER_ID = l.CUSTOMER_ID;

CREATE OR REPLACE VIEW V_W48_SCENARIO_COMPARE AS
SELECT s.*, a.TRANSPORTED_TONNES, a.AIR48_TONNES, a.RFS_TONNES,
       a.DEFERRED_TONNES, a.GROSS48_USD, a.RFS_COST_USD,
       s.NET48_USD * 0.25 AS SIMPLE_CONTRIBUTION48_USD,
       a.GROSS48_USD - a.RFS_COST_USD - s.CHARTER_COST_USD AS CALCULATED_NET48_USD,
       (a.GROSS48_USD + s.DEFERRED49_USD) * 0.25
           - a.RFS_COST_USD - s.CHARTER_COST_USD AS CALCULATED_MODEL_CONTRIBUTION_USD
FROM FACT_W48_SCENARIO s
LEFT JOIN (
    SELECT SCENARIO_ID,
           SUM(CASE WHEN MODE_ID <> 'yok' THEN TONNES ELSE 0 END) AS TRANSPORTED_TONNES,
           SUM(CASE WHEN MODE_ID IN ('akt','pas','krg','bel') THEN TONNES ELSE 0 END)
               AS AIR48_TONNES,
           SUM(CASE WHEN MODE_ID = 'rfs' THEN TONNES ELSE 0 END) AS RFS_TONNES,
           SUM(CASE WHEN MODE_ID = 'pzt' THEN TONNES ELSE 0 END) AS DEFERRED_TONNES,
           SUM(REVENUE48_USD) AS GROSS48_USD, SUM(RFS_COST_USD) AS RFS_COST_USD
    FROM FACT_W48_ALLOCATION GROUP BY SCENARIO_ID
) a ON s.SCENARIO_ID = a.SCENARIO_ID;

CREATE OR REPLACE VIEW V_LOYALTY_BUDGET AS
SELECT SUM(BASE_COST_USD) AS BASE_COST_USD, SUM(STRESS_COST_USD) AS STRESS_COST_USD,
       SUM(CASE WHEN BENEFIT_ID <> 'B01' THEN BASE_COST_USD ELSE 0 END) AS FIXED_COST_USD,
       SUM(CASE WHEN BENEFIT_ID = 'B01' THEN BASE_COST_USD ELSE 0 END) AS REBATE_USD,
       200000.0 AS BUDGET_USD, SUM(BASE_COST_USD) / 200000.0 AS BUDGET_USE_RATIO,
       200000.0 - SUM(BASE_COST_USD) AS REMAINING_BUDGET_USD,
       SUM(BASE_COST_USD) / 0.25 AS BREAK_EVEN_REVENUE_USD
FROM FACT_LOYALTY_COST;


CREATE OR REPLACE VIEW V_W48_ALLOCATION AS
SELECT a.*, s.SCENARIO_NAME
FROM FACT_W48_ALLOCATION a
JOIN FACT_W48_SCENARIO s ON a.SCENARIO_ID = s.SCENARIO_ID
WHERE s.SCENARIO_NAME IN ('Plan A', 'Plan B');

CREATE OR REPLACE VIEW V_CAPACITY_COMPARE AS
SELECT CAPACITY_ID,
       CASE CAPACITY_ID
           WHEN 'C01' THEN 'B777F'
           WHEN 'C02' THEN 'A330-200F'
           WHEN 'C03' THEN 'Belly toplamı'
           WHEN 'C04' THEN 'Toplam hava kapasitesi'
           WHEN 'C05' THEN 'Aktif çözüm sınırı'
       END AS CAPACITY_NAME, NORMAL_TONNES, CURRENT_TONNES
FROM FACT_W48_CAPACITY WHERE NORMAL_TONNES IS NOT NULL;

CREATE OR REPLACE VIEW V_CAPACITY_EXTRA AS
SELECT CAPACITY_NAME, CURRENT_TONNES
FROM FACT_W48_CAPACITY WHERE NORMAL_TONNES IS NULL;

-- Avantaj matrisi maliyet ve garanti tonunu ayrı sütunlarda tutar.
CREATE OR REPLACE VIEW V_LOYALTY_MATRIX AS
SELECT CUSTOMER_ID,
       SUM(CASE WHEN BENEFIT_ID = 'B01' THEN BASE_COST_USD ELSE 0 END) AS REBATE_USD,
       SUM(GUARANTEE_TONNES) AS GUARANTEE_TONNES,
       SUM(ACTIVE_GUARANTEE_TONNES) AS ACTIVE_GUARANTEE_TONNES,
       SUM(CASE WHEN BENEFIT_ID = 'B03' THEN BASE_COST_USD ELSE 0 END) AS CIP_USD,
       SUM(CASE WHEN BENEFIT_ID = 'B04' THEN BASE_COST_USD ELSE 0 END) AS SUPPORT_USD,
       SUM(CASE WHEN BENEFIT_ID = 'B05' THEN BASE_COST_USD ELSE 0 END) AS SUMMIT_USD,
       SUM(CASE WHEN BENEFIT_ID = 'B06' THEN BASE_COST_USD ELSE 0 END) AS SCORECARD_USD,
       SUM(CASE WHEN BENEFIT_ID = 'B07' THEN BASE_COST_USD ELSE 0 END) AS TRAINING_USD,
       SUM(CASE WHEN BENEFIT_ID = 'B08' THEN BASE_COST_USD ELSE 0 END) AS VISITS_USD
FROM FACT_LOYALTY_COST GROUP BY CUSTOMER_ID;
